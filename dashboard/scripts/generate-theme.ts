import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { themeConfig } from '../src/theme/_config'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const output = resolve(root, 'src/theme/generated/tokens.css')

const toKebab = (value: string) =>
  value.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()

const hexToRgb = (hex: string) => {
  const value = hex.replace('#', '')
  if (!/^[0-9a-fA-F]{6}$/.test(value)) return null

  return [
    Number.parseInt(value.slice(0, 2), 16),
    Number.parseInt(value.slice(2, 4), 16),
    Number.parseInt(value.slice(4, 6), 16),
  ].join(' ')
}

const rawVariables = Object.entries(themeConfig.colors)
  .map(([key, value]) => `  --color-${toKebab(key)}: ${value};`)
  .join('\n')

const appVariables = (variant: keyof typeof themeConfig.app) =>
  Object.entries(themeConfig.app[variant])
    .flatMap(([key, value]) => {
      const token = toKebab(key)
      const rgb = hexToRgb(value)
      return [
        `  --app-${token}: ${value};`,
        ...(rgb ? [`  --app-${token}-rgb: ${rgb};`] : []),
      ]
    })
    .join('\n')

const rawUtilities = Object.keys(themeConfig.colors)
  .flatMap((key) => {
    const variable = `var(--color-${toKebab(key)})`
    return [
      `.bg-${key} { background-color: ${variable}; }`,
      `.text-${key} { color: ${variable}; }`,
      `.border-${key} { border-color: ${variable}; }`,
    ]
  })
  .join('\n')

const css = `/* AUTO-GENERATED by scripts/generate-theme.ts. Do not edit directly. */
:root {
${rawVariables}
${appVariables('light')}
  --radius-button: ${themeConfig.radius.button}px;
  --radius-card: ${themeConfig.radius.card}px;
  --radius-sheet: ${themeConfig.radius.sheet}px;
  --radius-pill: ${themeConfig.radius.pill}px;
  --shadow-top: ${themeConfig.shadows.top};
  --shadow-card: ${themeConfig.shadows.card};
  --shadow-report: ${themeConfig.shadows.report};
}

.dark {
${appVariables('dark')}
}

${rawUtilities}
`

await mkdir(dirname(output), { recursive: true })
await writeFile(output, css, 'utf8')
console.log(`Generated ${output}`)
